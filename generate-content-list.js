// generate-content-list.js
// Scans the /content folder for archive files (.zip) and writes
// content-list.js, a manifest the browser can fetch without needing
// server-side directory listing (which static hosts like Vercel don't provide).
//
// Runs automatically on every Vercel build via the "build" script in package.json.

const fs = require("fs");
const path = require("path");

const CONTENT_DIR = path.join(__dirname, "content");
const OUTPUT_FILE = path.join(__dirname, "content-list.js");
const ARCHIVE_EXTENSIONS = [".zip"];

function findArchives(dir) {
  if (!fs.existsSync(dir)) {
    console.warn(`Content folder not found at ${dir}, generating empty manifest.`);
    return [];
  }

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const archives = [];

  for (const entry of entries) {
    if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (ARCHIVE_EXTENSIONS.includes(ext)) {
        archives.push(`content/${entry.name}`);
      }
    }
  }

  return archives.sort();
}

const archives = findArchives(CONTENT_DIR);

const fileContent = `// AUTO-GENERATED by generate-content-list.js — do not edit by hand.
// Regenerated on every build from the contents of /content.
window.CONTENT_ARCHIVES = ${JSON.stringify(archives, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, fileContent, "utf8");
console.log(`Found ${archives.length} archive(s) in /content:`);
archives.forEach((a) => console.log(`  - ${a}`));
console.log(`Wrote manifest to ${OUTPUT_FILE}`);
